/**
 * Generates src/shape/MaterialShapeData.ts: the 35 Material 3 Expressive shapes as AndroidX
 * RoundedPolygon features (normalised to the unit square), so they can be rendered and morphed
 * exactly like Compose's `MaterialShapes` + `Morph`.
 *
 * Geometry comes from `material-shapes-ts` (Apache-2.0), a TypeScript port of AndroidX
 * graphics-shapes + MaterialShapes.kt. Its shape definitions were checked against
 * MaterialShapes.kt (androidx-main); the one divergence (Circle uses 10 vertices in AndroidX,
 * not 8) is corrected below.
 *
 * Run: node packages/web/scripts/gen-material-shapes.mjs
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { MaterialShapes, Shapes, Corner } from "material-shapes-ts";

/** AndroidX name -> m3e kebab-case ShapeName. */
const NAMES = {
  Circle: "circle",
  Square: "square",
  Slanted: "slanted",
  Arch: "arch",
  Fan: "fan",
  Arrow: "arrow",
  SemiCircle: "semicircle",
  Oval: "oval",
  Pill: "pill",
  Triangle: "triangle",
  Diamond: "diamond",
  ClamShell: "clamshell",
  Pentagon: "pentagon",
  Gem: "gem",
  VerySunny: "very-sunny",
  Sunny: "sunny",
  Cookie4Sided: "4-sided-cookie",
  Cookie6Sided: "6-sided-cookie",
  Cookie7Sided: "7-sided-cookie",
  Cookie9Sided: "9-sided-cookie",
  Cookie12Sided: "12-sided-cookie",
  Clover4Leaf: "4-leaf-clover",
  Clover8Leaf: "8-leaf-clover",
  Burst: "burst",
  SoftBurst: "soft-burst",
  Boom: "boom",
  SoftBoom: "soft-boom",
  Flower: "flower",
  Puffy: "puffy",
  PuffyDiamond: "puffy-diamond",
  Ghostish: "ghost-ish",
  PixelCircle: "pixel-circle",
  PixelTriangle: "pixel-triangle",
  Bun: "bun",
  Heart: "heart",
};

const P = 1e4;
const r = (v) => Math.round(v * P) / P;

const polygonFor = (name) =>
  // MaterialShapes.kt: `internal fun circle(numVertices: Int = 10)`.
  name === "Circle" ? Shapes.circle(10).normalized() : MaterialShapes.byName(name);

const entries = [];
for (const name of MaterialShapes.names) {
  const key = NAMES[name];
  if (!key) throw new Error(`Unmapped shape ${name}`);
  const poly = polygonFor(name);
  const features = poly.features.map((f) => {
    const t = f instanceof Corner ? (f.convex ? "x" : "o") : "e";
    const c = f.cubics;
    const nums = [c[0].anchor0X, c[0].anchor0Y];
    for (const q of c) nums.push(q.control0X, q.control0Y, q.control1X, q.control1Y, q.anchor1X, q.anchor1Y);
    return `["${t}",[${nums.map(r).join(",")}]]`;
  });
  entries.push(`  "${key}": { c: [${r(poly.centerX)}, ${r(poly.centerY)}], f: [${features.join(",")}] },`);
}

const out = `// prettier-ignore
// GENERATED by scripts/gen-material-shapes.mjs. Do not edit by hand.
//
// The 35 Material 3 Expressive shapes (AndroidX Compose \`MaterialShapes\`), as RoundedPolygon
// features in the unit square. Ported from AndroidX graphics-shapes via material-shapes-ts.
// Copyright 2024 The Android Open Source Project. Licensed under the Apache License, Version 2.0.

/** Feature kind: "x" convex corner, "o" concave corner, "e" edge. */
export type MaterialShapeFeatureKind = "x" | "o" | "e";

/**
 * A feature: its kind and its cubics as one flat list,
 * \`[a0x, a0y, c0x, c0y, c1x, c1y, a1x, a1y, c0x, c0y, ...]\` (each cubic starts where the last ended).
 */
export type MaterialShapeFeature = readonly [MaterialShapeFeatureKind, readonly number[]];

/** A shape: its center and its features, in order around the outline. */
export interface MaterialShapeData {
  readonly c: readonly [number, number];
  readonly f: readonly MaterialShapeFeature[];
}

/** Specifies the names of the 35 Material shapes. */
export type MaterialShapeName =
${Object.values(NAMES).map((n) => `  | "${n}"`).join("\n")};

/** The 35 Material shapes, keyed by name, in AndroidX chart order. */
export const MaterialShapeData: Record<MaterialShapeName, MaterialShapeData> = {
${entries.join("\n")}
};

/** Returns the SVG path data (unit square, \`viewBox="0 0 1 1"\`) for a shape. */
export function materialShapePath(name: MaterialShapeName, size = 1): string {
  const s = (v: number) => +(v * size).toFixed(3);
  let d = "";
  for (const [, n] of MaterialShapeData[name].f) {
    if (!d) d = \`M\${s(n[0])} \${s(n[1])}\`;
    for (let i = 2; i < n.length; i += 6)
      d += \`C\${s(n[i])} \${s(n[i + 1])} \${s(n[i + 2])} \${s(n[i + 3])} \${s(n[i + 4])} \${s(n[i + 5])}\`;
  }
  return d + "Z";
}
`;
const target = fileURLToPath(new URL("../src/shape/MaterialShapeData.ts", import.meta.url));
writeFileSync(target, out);
console.log(`wrote ${entries.length} shapes, ${(out.length / 1024).toFixed(1)} KB -> ${target}`);
